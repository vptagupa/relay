// collapsedBlocks + fmtDur + the block renderers (blockHtml/bvBlockHtml) live in ./block-view.
// ANSI text helpers live in ./ansi (renderer still uses stripAnsi/collapseCR directly).
// Structured command blocks stream in from the shell-integration parser (main process).
relay.onPtyBlock((id: string, ev: { type: 'start' | 'update' | 'end'; block: Block } | { type: 'cwd'; cwd: string }) => {
  const t = state.tabs.find((x) => x.id === id); if (!t) return;
  // The shell reported its working directory (fires each prompt) — keep the tab's cwd live so the
  // cd autocomplete lists the *current* folder and the status bar stays accurate after a `cd`.
  if (ev.type === 'cwd') {
    if (ev.cwd && ev.cwd !== t.cwd) { t.cwd = ev.cwd; if (state.active === id) updateStatus(); }
    runStartupIfPending(id); // a template's startup command runs on the terminal's first prompt (shell ready)
    return;
  }
  // Namespace the parser's per-run ids (b1, b2, …) with a per-tab nonce so a fresh shell's
  // blocks never collide with blocks restored from a previous run of the same terminal.
  const bid = t.bkNonce + ':' + ev.block.id;
  const blk: Block = { ...ev.block, id: bid };
  const i = t.blocks.findIndex((b) => b.id === bid);
  if (i >= 0) t.blocks[i] = { ...blk, pinned: t.blocks[i].pinned };
  else t.blocks.push(blk);
  if (t.blocks.length > 500) t.blocks.splice(0, t.blocks.length - 500);
  // A full-screen app entered alt-screen → drop the Blocks view to the live terminal so
  // vim/top run interactively; when its block ends (app exited), return to the Blocks view.
  const visible = leaves(state.layout).some((g) => state.gv[g] === t.id);
  if (blk.interactive && !t.liveInteractive) { t.liveInteractive = true; if (visible) updateMainView(); }
  if (ev.type === 'end' && t.liveInteractive) { t.liveInteractive = false; if (visible) updateMainView(); }
  if (visible) refreshBlockViews();
  if (ev.type === 'end') { maybeNotify(t, blk); persistWorkspace(); }
});
// Desktop notification when a long-running command finishes while Relay is unfocused.
const NOTIFY_MIN_MS = 8000;
function maybeNotify(t: Tab, b: Block) {
  if (!state.settings.notifications || b.interactive || b.running || b.exitCode == null) return;
  if (document.hasFocus()) return; // only when the window isn't focused
  const dur = (b.endedAt || 0) - (b.startedAt || 0);
  if (dur < NOTIFY_MIN_MS) return;
  const cmd = cmdText(b) || 'command'; const ok = b.exitCode === 0;
  try {
    const n = new Notification(`${ok ? '✓' : '✗'} ${cmd.slice(0, 64)}`, { body: `${t.name} · ${ok ? 'done' : 'exit ' + b.exitCode} · ${fmtDur(dur)}` });
    n.onclick = () => { relay.winFocus?.(); switchTab(t.id); };
  } catch { /* notifications unavailable */ }
}
